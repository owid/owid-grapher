import { describe, expect, it } from "vitest"
import { ExplorerType, OwidColumnDef } from "@ourworldindata/types"
import { addDuplicateYVariableIds } from "./explorerViewsLogic.js"
import { ExplorerViewBaseRecord } from "./types.js"

function makeRecord(
    overrides: Partial<ExplorerViewBaseRecord>
): ExplorerViewBaseRecord {
    return {
        explorerType: ExplorerType.Csv,
        availableEntities: [],
        numNonDefaultSettings: 0,
        viewIndexWithinExplorer: 0,
        viewQueryParams: "",
        viewId: "",
        viewSettings: [],
        ySlugs: [],
        yVariableIds: [],
        explorerSlug: "test-explorer",
        ...overrides,
    }
}

// Indicator explorers generated by the ETL can reference indicators only via
// `ySlugs` pointing at columns with a `duplicate <variableId>` transform. Those
// views must be indexed as indicator views, not as CSV views (which would need
// a tableSlug and get dropped from search).
describe(addDuplicateYVariableIds, () => {
    const duplicateTransforms: OwidColumnDef[] = [
        { slug: "population_low", transform: "duplicate 953298" },
        { slug: "population_high", transform: "duplicate 953299" },
    ]

    it("turns a view whose ySlugs are duplicate transforms into an indicator view", () => {
        const [record] = addDuplicateYVariableIds(
            [makeRecord({ ySlugs: ["population_low", "population_high"] })],
            duplicateTransforms
        )

        expect(record.explorerType).toBe(ExplorerType.Indicator)
        expect(record.yVariableIds).toEqual([953298, 953299])
    })

    it("keeps a CSV view whose ySlugs aren't duplicate transforms", () => {
        const [record] = addDuplicateYVariableIds(
            [makeRecord({ ySlugs: ["gdp"], tableSlug: "gdp_table" })],
            duplicateTransforms
        )

        expect(record.explorerType).toBe(ExplorerType.Csv)
        expect(record.yVariableIds).toEqual([])
    })

    it("keeps a grapher view a grapher view", () => {
        const [record] = addDuplicateYVariableIds(
            [
                makeRecord({
                    explorerType: ExplorerType.Grapher,
                    viewGrapherId: 123,
                    ySlugs: ["population_low"],
                }),
            ],
            duplicateTransforms
        )

        expect(record.explorerType).toBe(ExplorerType.Grapher)
    })
})
