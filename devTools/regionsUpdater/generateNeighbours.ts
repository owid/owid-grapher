import { writeFile } from "fs/promises"
import { neighbors } from "topojson-client"
import type { GeometryObject, Topology } from "topojson-specification"
import { format, type FormatConfig } from "oxfmt"
import oxfmtConfig from "../../.oxfmtrc.json"
import { regions } from "@ourworldindata/utils"

/**
 * Generates `neighbours.data.ts`: the land neighbours of every entity on the
 * world map, keyed by entity code. Neighbours are derived from the shared
 * borders (arcs) in `MapTopology.ts`, plus the manual overrides below.
 *
 * Runs as part of `yarn runRegionsUpdater`, or standalone via
 * `yarn buildNeighboursData` (reads the checked-in MapTopology.ts).
 */

const GRAPHER_ROOT = __dirname.replace(/\/devTools.*/, ""),
    GRAPHER_TOPOLOGY_PATH = `${GRAPHER_ROOT}/packages/@ourworldindata/grapher/src/mapCharts/MapTopology.ts`,
    GRAPHER_NEIGHBOURS_PATH = `${GRAPHER_ROOT}/packages/@ourworldindata/utils/src/regions/neighbours.data.ts`

/**
 * Land borders that the map topology doesn't capture, added in both
 * directions. Keep this list short: borders between entities that are both
 * on the map should normally come from the topology.
 */
const NEIGHBOUR_OVERRIDES: [string, string, string][] = [
    // Entities not on the (low-res) map, or too small to share an arc
    ["AND", "ESP", "Andorra is too small to share a border on the map"],
    ["AND", "FRA", "Andorra is too small to share a border on the map"],
    ["MCO", "FRA", "Monaco is too small to share a border on the map"],
    ["SMR", "ITA", "San Marino is too small to share a border on the map"],
    ["VAT", "ITA", "Vatican isn't on the map"],
    ["GIB", "ESP", "Gibraltar isn't on the map"],
    ["HKG", "CHN", "Hong Kong isn't on the map"],
    ["MAC", "CHN", "Macao isn't on the map"],
    ["PSE", "EGY", "Gaza is added to the map as a separate polygon"],
    // Short borders lost in the map's simplification
    ["NOR", "RUS", "short border in the far north"],
    ["PRK", "RUS", "short border along the Tumen river"],
    ["AZE", "TUR", "via Nakhchivan"],
    ["EGY", "ISR", "Sinai border"],
    ["ALB", "MKD", "border along Lake Ohrid and Prespa"],
    ["ALB", "OWID_KOS", "simplification artefact"],
    ["HRV", "MNE", "short border south of Dubrovnik"],
    ["NGA", "TCD", "border in Lake Chad"],
    ["MWI", "TZA", "border along Lake Malawi"],
]

const GENERATED_FILE_HEADER = [
    "// This file is auto-generated by devTools/regionsUpdater/generateNeighbours.ts",
    "// Do not edit manually. Run `yarn buildNeighboursData` to regenerate.\n\n",
].join("\n")

interface RegionNameAndCode {
    code: string
    name: string
}

async function loadTopology(): Promise<Topology> {
    // Imported dynamically (and untyped) so that we read the file that
    // update.ts just wrote, and so that this project doesn't need a
    // reference to the grapher package
    const module: { MapTopology: Topology } = await import(
        GRAPHER_TOPOLOGY_PATH
    )
    return module.MapTopology
}

export function computeNeighbours(
    topology: Topology,
    regionsData: readonly RegionNameAndCode[]
): Record<string, string[]> {
    const codeByName = new Map(regionsData.map((r) => [r.name, r.code]))
    const knownCodes = new Set(regionsData.map((r) => r.code))
    const geometries = (
        topology.objects.world as { geometries: GeometryObject[] }
    ).geometries

    const neighbours = new Map<string, Set<string>>()
    const addPair = (a: string, b: string): void => {
        if (!neighbours.has(a)) neighbours.set(a, new Set())
        if (!neighbours.has(b)) neighbours.set(b, new Set())
        neighbours.get(a)!.add(b)
        neighbours.get(b)!.add(a)
    }

    const codeForGeometry = (geometry: GeometryObject): string | undefined => {
        const code = codeByName.get(String(geometry.id))
        if (!code)
            console.log(`⚠️  No region found for map entity ${geometry.id}`)
        return code
    }

    neighbors(geometries).forEach((neighbourIndices, index) => {
        const code = codeForGeometry(geometries[index])
        if (!code) return
        for (const neighbourIndex of neighbourIndices) {
            const neighbourCode = codeForGeometry(geometries[neighbourIndex])
            if (neighbourCode) addPair(code, neighbourCode)
        }
    })

    for (const [a, b] of NEIGHBOUR_OVERRIDES) {
        for (const code of [a, b])
            if (!knownCodes.has(code))
                throw new Error(`Unknown code in neighbour overrides: ${code}`)
        if (neighbours.get(a)?.has(b))
            console.log(
                `ℹ️  Neighbour override ${a}–${b} is now covered by the map and can be removed`
            )
        addPair(a, b)
    }

    return Object.fromEntries(
        [...neighbours.entries()]
            .sort(([a], [b]) => a.localeCompare(b))
            .map(([code, codes]) => [
                code,
                [...codes].sort((a, b) => a.localeCompare(b)),
            ])
    )
}

export async function generateNeighboursData(
    regionsData: readonly RegionNameAndCode[] = regions
): Promise<void> {
    const neighbours = computeNeighbours(await loadTopology(), regionsData)
    const result = await format(
        "input.ts",
        GENERATED_FILE_HEADER +
            `import type { EntityCode } from "@ourworldindata/types"\n\n` +
            `/** Land neighbours by entity code; entities without neighbours are omitted */\n` +
            `export const neighboursData: Record<EntityCode, EntityCode[]> = ${JSON.stringify(neighbours)}`,
        oxfmtConfig as FormatConfig
    )
    await writeFile(GRAPHER_NEIGHBOURS_PATH, result.code)
    console.log(
        `Wrote neighbours of ${Object.keys(neighbours).length} entities to ${GRAPHER_NEIGHBOURS_PATH}`
    )
}

if (require.main === module) void generateNeighboursData()
